import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const base=process.env.WONY_BASE_URL||'http://127.0.0.1:8000';
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox','--enable-unsafe-swiftshader','--use-gl=angle','--use-angle=swiftshader']});
const page=await browser.newPage({baseURL:base,viewport:{width:1440,height:1200}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try{
  await page.goto('/demo/');
  await page.locator('#player-id').fill('BROWSER-SCOUT');
  await page.locator('#analysis-date').fill('2026-10-10');
  await page.locator('#comparison-context').fill('same-side-camera');
  await page.locator('#demo').click();
  await page.waitForFunction(()=>document.getElementById('source-badge').textContent.includes('DEMO'));
  await page.locator('#scouting-tab').click();
  assert(await page.locator('#scouting-panel').isVisible());
  assert.equal(await page.locator('.rating-card').count(),5);
  assert.equal(await page.locator('.role-report').count(),5);
  assert.match(await page.locator('#report-player').textContent(),/BROWSER-SCOUT.*2026-10-10/);
  assert.match(await page.locator('#report-source').textContent(),/DEMO/);
  assert(await page.locator('.play-card').count()>0);
  await page.locator('.play-card button').first().click();
  assert(await page.locator('#motion-panel').isVisible());
  assert.match(await page.locator('#frame-counter').textContent(),/FRAME/);
  await page.locator('#scouting-tab').click();
  await page.locator('#demo-growth').click();
  await page.waitForFunction(()=>document.getElementById('growth-notice').textContent.includes('임의 점수'));
  assert.match(await page.locator('#growth-report').textContent(),/\+9/);
  assert.match(await page.locator('#growth-report').textContent(),/\+6/);
  await page.screenshot({path:path.join(root,'docs/screenshots/scouting-report.png'),fullPage:true});
  await page.locator('#load-history').click();
  await page.waitForFunction(()=>document.getElementById('growth-notice').textContent.includes('DEMO 기록만'));
  assert(await page.locator('#growth-report button').count()>0);
  await page.locator('#growth-report button').first().click();
  await page.waitForFunction(()=>!document.getElementById('motion-panel').hidden);
  await page.locator('[data-role="baserunning"]').click();await page.locator('#demo').click();
  await page.waitForFunction(()=>document.getElementById('source-badge').textContent.startsWith('주루'));
  await page.locator('#scouting-tab').click();
  assert.match(await page.locator('#role-reports').textContent(),/start reaction/);
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  assert.deepEqual(errors,[]);
  console.log('PASS: scouting tab, 5 role evaluations, withheld ratings, player/date fields, play-to-visualization navigation, DEMO growth +9/+6 labels, source-separated history, historical visualization, baserunning and mobile layout.');
}finally{await browser.close();}
